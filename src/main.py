import json
import os
from pathlib import Path
from threading import Lock

from fastapi import FastAPI, HTTPException
from pydantic import BaseModel
import ollama
from dotenv import load_dotenv

# Load environment variables from .env file
load_dotenv()

# Initialize the FastAPI app
app = FastAPI(
    title="AI Agent API",
    description="An API for interacting with an AI agent and providing feedback.",
    version="0.1.0",
)

# Feedback is persisted as JSON Lines under this path (one record per line).
# Override with FEEDBACK_STORE_PATH for tests or alternate deployments.
FEEDBACK_STORE_PATH = Path(
    os.getenv("FEEDBACK_STORE_PATH", "data/feedback.jsonl")
)
_feedback_lock = Lock()


def _ensure_store_parent(path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)


def save_feedback(record: dict, path: Path | None = None) -> None:
    """Append a feedback record to the JSONL store."""
    store_path = path or FEEDBACK_STORE_PATH
    _ensure_store_parent(store_path)
    line = json.dumps(record, ensure_ascii=False) + "\n"
    with _feedback_lock:
        with store_path.open("a", encoding="utf-8") as f:
            f.write(line)


def load_feedback(feedback_id: str, path: Path | None = None) -> dict | None:
    """Return a stored feedback record by id, or None if not found."""
    store_path = path or FEEDBACK_STORE_PATH
    if not store_path.exists():
        return None
    with _feedback_lock:
        with store_path.open("r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                record = json.loads(line)
                if record.get("feedback_id") == feedback_id:
                    return record
    return None


# --- Pydantic Models ---
class GenerateRequest(BaseModel):
    prompt: str
    model: str = os.getenv("OLLAMA_MODEL", "llama2")  # Default model from env or hardcoded

class GenerateResponse(BaseModel):
    response: str

class FeedbackRequest(BaseModel):
    prompt: str
    response: str
    is_correct: bool
    correction: str | None = None

class FeedbackResponse(BaseModel):
    message: str
    feedback_id: str  # A unique ID for the feedback record

# --- API Endpoints ---

@app.get("/", summary="Health Check", description="Check if the API is running.")
def read_root():
    """
    Root endpoint to check if the API is up and running.
    """
    return {"status": "ok"}


@app.post("/api/generate", response_model=GenerateResponse, summary="Generate Agent Response")
async def generate(request: GenerateRequest):
    """
    Generates a response from the specified Ollama model based on the prompt.

    - **prompt**: The input text to the model.
    - **model**: The name of the Ollama model to use (e.g., 'llama2', 'codellama').
    """
    try:
        ollama_response = ollama.chat(
            model=request.model,
            messages=[{'role': 'user', 'content': request.prompt}]
        )
        response_content = ollama_response['message']['content']
        return GenerateResponse(response=response_content)
    except Exception as e:
        # Broad exception for now, can be refined
        raise HTTPException(status_code=500, detail=str(e))


@app.post("/api/feedback", response_model=FeedbackResponse, summary="Submit Feedback")
async def feedback(request: FeedbackRequest):
    """
    Submits feedback on a generated response. Feedback is persisted to a local
    JSONL store for later fine-tuning and review.

    - **prompt**: The original prompt.
    - **response**: The response generated by the agent.
    - **is_correct**: A boolean indicating if the response was correct.
    - **correction**: (Optional) The corrected version of the response.
    """
    feedback_id = os.urandom(16).hex()
    record = {
        "feedback_id": feedback_id,
        "prompt": request.prompt,
        "response": request.response,
        "is_correct": request.is_correct,
        "correction": request.correction,
    }
    try:
        save_feedback(record)
    except OSError as e:
        raise HTTPException(
            status_code=500,
            detail=f"Failed to persist feedback: {e}",
        ) from e

    return FeedbackResponse(
        message="Feedback received successfully. Thank you!",
        feedback_id=feedback_id,
    )
